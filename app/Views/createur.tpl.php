<h2> Les createurs </h2>

        <h3>Hirokazu Yasuhara </h3>
        <p> Hirokazu Yasuhara (安原 広和?) est un designer japonais de jeu vidéo. Ancien membre important du studio Sonic Team, 
            il a occupé des fonctions artistiques chez Naughty Dog, et plus récemment pour Namco Bandai. 
        </p>

        <h3>Yuji Naka </h3>
        <p> Yuji Naka est un développeur de jeux vidéo né le 17 septembre 1965 au Japon.
        Il a été programmeur principal sur le jeu Sonic the Hedgehog.En 2002, il reçoit un Game Developers 
        Choice Award pour l'ensemble de sa carrière. 
        </p>

        <h3>Naoto Ōshima/h3>
        <p> Naoto Ōshima (大島 直人?) est un designer japonais de jeu vidéo, ancien employé de Sega, principalement connu 
        pour avoir modelé le design de Sonic et Eggman.Après avoir quitté Sonic Team, Ōshima fonde un studio de développement
        indépendant nommé Artoon. 
        </p>

